type OP = { x: number; z: number; w: number; kind: 'back' | 'end' | 'live' };

function slabOutline(): OP[] {
  const { x0, x1, back } = SLAB;
  const pts: OP[] = [];
  const rNW = 0.045, rNE = 0.012, rF = 0.016;
  const arc = (cx: number, cz: number, r: number, a0: number, a1: number, n: number, w0: number, w1: number, k0: OP['kind'], k1: OP['kind']) => {
    for (let i = 0; i <= n; i++) {
      const t = i / n, a = a0 + (a1 - a0) * t;
      pts.push({ x: cx + Math.cos(a) * r, z: cz + Math.sin(a) * r, w: w0 + (w1 - w0) * ease(t), kind: t < 0.5 ? k0 : k1 });
    }
  };
  // back edge, west → east (z = back); CCW in (x, z)
  const nb = Math.ceil((x1 - rNE - (x0 + rNW)) / 0.02);
  for (let i = 1; i < nb; i++) pts.push({ x: x0 + rNW + ((x1 - rNE - x0 - rNW) * i) / nb, z: back, w: 0, kind: 'back' });
  arc(x1 - rNE, back + rNE, rNE, -Math.PI / 2, 0, 5, 0, 0, 'back', 'end');
  // east end, back → front
  const zF1 = liveZ(x1 - rF);
  const ne = Math.ceil((zF1 - rF - (back + rNE)) / 0.02);
  for (let i = 1; i < ne; i++) pts.push({ x: x1, z: back + rNE + ((zF1 - rF - back - rNE) * i) / ne, w: 0, kind: 'end' });
  arc(x1 - rF, zF1 - rF, rF, 0, Math.PI / 2, 7, 0, 1, 'end', 'live');
  // live front edge, east → west, 5 mm steps
  const nl = Math.ceil((x1 - x0 - 2 * rF) / 0.005);
  for (let i = 1; i < nl; i++) {
    const x = x1 - rF - ((x1 - x0 - 2 * rF) * i) / nl;
    pts.push({ x, z: liveZ(x), w: 1, kind: 'live' });
  }
  const zF0 = liveZ(x0 + rF);
  arc(x0 + rF, zF0 - rF, rF, Math.PI / 2, Math.PI, 7, 1, 0, 'live', 'end');
  // west end, front → back
  const nw = Math.ceil((zF0 - rF - (back + rNW)) / 0.02);
  for (let i = 1; i < nw; i++) pts.push({ x: x0, z: zF0 - rF - ((zF0 - rF - back - rNW) * i) / nw, w: 0, kind: 'end' });
  arc(x0 + rNW, back + rNW, rNW, Math.PI, 1.5 * Math.PI, 8, 0, 0, 'end', 'back');
  // drop the duplicate last point (== first of arc joins)
  return pts;
}

/** inward offset of the slab surface at outline weight w (live), depth fraction t (0 top … 1 bottom) */
function slabInset(p: OP, t: number) {
  const th = SLAB.thick, d = t * th;
  // cut edges: 2 mm eased arris top and bottom
  const cut = d < 0.002 ? 0.002 - Math.sqrt(Math.max(0, 0.002 * 0.002 - (0.002 - d) * (0.002 - d))) : d > th - 0.0015 ? 0.0015 - Math.sqrt(Math.max(0, 0.0015 * 0.0015 - (d - th + 0.0015) ** 2)) : 0;
  if (p.w <= 0) return cut;
  const s = p.x;
  const r = 0.009 + 0.003 * vnoise(s * 9, 1.3); // rounded rim
  const rim = d < r ? r - Math.sqrt(Math.max(0, r * r - (r - d) * (r - d))) : 0;
  const under = (0.02 + 0.012 * vnoise(s * 3.1, 7.7) + 0.006 * Math.sin(s * 8.3)) * Math.pow(smooth(0.22, 1.0, t), 1.25);
  const bumps = (0.0032 * vnoise(s * 55, t * 7) + 0.0022 * vnoise(s * 140, t * 16 + 4) + 0.0012 * vnoise(s * 400, t * 30)) * smooth(0.12, 0.35, t);
  // occasional deeper bark-scar gouges
  const g = vnoise(s * 18, 3.3);
  const gouge = g > 0.28 ? (g - 0.28) * 0.03 * smooth(0.3, 0.6, t) : 0;
  const live = rim + under + bumps + gouge;
  return cut * (1 - p.w) + live * p.w;
}

function slabGeometry() {
  const out = slabOutline();
  const N = out.length;
  // inward normals of the outline (CCW in x,z → left normal points inside)
  const inward = out.map((_, i) => {
    const a = out[(i - 1 + N) % N], b = out[(i + 1) % N];
    const tx = b.x - a.x, tz = b.z - a.z, l = Math.hypot(tx, tz) || 1;
    return [-tz / l, tx / l] as [number, number];
  });
  // sanity: CCW check (area > 0)
  let area = 0;
  for (let i = 0; i < N; i++) area += out[i].x * out[(i + 1) % N].z - out[(i + 1) % N].x * out[i].z;
  const flip = area < 0 ? -1 : 1;
  const ts = [0, 0.012, 0.035, 0.07, 0.12, 0.19, 0.28, 0.38, 0.48, 0.58, 0.68, 0.77, 0.85, 0.92, 0.965, 0.99, 1];
  const K = ts.length;
  const P: THREE.Vector3[][] = [];
  for (let k = 0; k < K; k++) {
    const row: THREE.Vector3[] = [];
    for (let i = 0; i < N; i++) {
      const p = out[i], inset = slabInset(p, ts[k]) * flip;
      row.push(new THREE.Vector3(p.x + inward[i][0] * inset, SLAB.top - ts[k] * SLAB.thick, p.z + inward[i][1] * inset));
    }
    P.push(row);
  }
  // analytic-ish normals from the grid (central differences, wrapping around the outline)
  const Nrm: THREE.Vector3[][] = [];
  for (let k = 0; k < K; k++) {
    const row: THREE.Vector3[] = [];
    for (let i = 0; i < N; i++) {
      const ds = P[k][(i + 1) % N].clone().sub(P[k][(i - 1 + N) % N]);
      const dt = P[Math.min(K - 1, k + 1)][i].clone().sub(P[Math.max(0, k - 1)][i]);
      const n = new THREE.Vector3().crossVectors(dt, ds).normalize();
      // ensure outward (away from the inward normal)
      if (n.x * inward[i][0] * flip + n.z * inward[i][1] * flip > 0) n.negate();
      row.push(n);
    }
    Nrm.push(row);
  }
  const uTop = (x: number) => (x - UVF.xa) / (UVF.xb - UVF.xa);
  const vTop = (z: number) => 1 - (z - UVF.za) / (UVF.zb - UVF.za);
  const pos: number[] = [], nor: number[] = [], uv: number[] = [];
  const groups: { start: number; count: number; mat: number }[] = [];
  let vcount = 0;
  const idx: number[] = [];
  const emitGroup = (mat: number, fn: () => void) => {
    const start = idx.length;
    fn();
    groups.push({ start, count: idx.length - start, mat });
  };
  const vert = (p: THREE.Vector3, n: THREE.Vector3, u: number, v: number) => {
    pos.push(p.x, p.y, p.z);
    nor.push(n.x, n.y, n.z);
    uv.push(u, v);
    return vcount++;
  };
  // --- sides: split into runs of the same material, each run gets its own vertex strip
  const matOf = (p: OP) => (p.kind === 'live' ? 1 : p.kind === 'end' ? 2 : 0);
  const runs: { mat: number; ids: number[] }[] = [];
  for (let i = 0; i < N; i++) {
    const m = matOf(out[i]);
    if (!runs.length || runs[runs.length - 1].mat !== m) runs.push({ mat: m, ids: [] });
    runs[runs.length - 1].ids.push(i);
  }
  // close each run with the first index of the next run so there are no gaps
  for (let r = 0; r < runs.length; r++) runs[r].ids.push(runs[(r + 1) % runs.length].ids[0]);
  if (runs.length > 1 && runs[0].mat === runs[runs.length - 1].mat) {
    // merge wrap-around run
    const last = runs.pop()!;
    runs[0].ids = [...last.ids.slice(0, -1), ...runs[0].ids];
  }
  const sideUV = (mat: number, i: number, k: number): [number, number] => {
    const p = out[i], t = ts[k];
    if (mat === 1) return [uTop(p.x), 1 - t];
    if (mat === 2) return [(p.z - UVF.za) / (UVF.xb - UVF.xa) + 0.13, 0.5 - (t * SLAB.thick) / (UVF.zb - UVF.za)];
    return [uTop(p.x), vTop(p.z) + (0.004 + t * 0.045) / (UVF.zb - UVF.za)];
  };
  for (const run of runs) {
    emitGroup(run.mat, () => {
      const base: number[][] = [];
      for (let k = 0; k < K; k++) base.push(run.ids.map((i) => vert(P[k][i], Nrm[k][i], ...sideUV(run.mat, i, k))));
      for (let k = 0; k < K - 1; k++)
        for (let j = 0; j < run.ids.length - 1; j++) {
          const a = base[k][j], b = base[k][j + 1], c = base[k + 1][j], d = base[k + 1][j + 1];
          if (flip > 0) idx.push(a, b, c, b, d, c);
          else idx.push(a, c, b, b, c, d);
        }
    });
  }
  // --- caps
  const cap = (k: number, up: boolean, mat: number) => {
    const contour = P[k].map((p) => new THREE.Vector2(p.x, p.z));
    const tris = THREE.ShapeUtils.triangulateShape(contour, []);
    const n = new THREE.Vector3(0, up ? 1 : -1, 0);
    emitGroup(mat, () => {
      const ids = P[k].map((p) => vert(p, n, uTop(p.x), vTop(p.z)));
      for (const [a, b, c] of tris) {
        // shape winding in (x,z): decide orientation so the face normal matches n
        const A = P[k][a], B = P[k][b], C = P[k][c];
        const ny = (B.z - A.z) * (C.x - A.x) - (B.x - A.x) * (C.z - A.z);
        if (ny > 0 === up) idx.push(ids[a], ids[b], ids[c]);
        else idx.push(ids[a], ids[c], ids[b]);
      }
    });
  };
  cap(0, true, 0);
  cap(K - 1, false, 3);
  const g = new THREE.BufferGeometry();
  g.setAttribute('position', new THREE.Float32BufferAttribute(pos, 3));
  g.setAttribute('normal', new THREE.Float32BufferAttribute(nor, 3));
  g.setAttribute('uv', new THREE.Float32BufferAttribute(uv, 2));
  g.setIndex(idx);
  for (const gr of groups) g.addGroup(gr.start, gr.count, gr.mat);
  return g;
}

