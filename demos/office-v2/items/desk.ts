const ease = (t: number) => t * t * (3 - 2 * t);
const clamp01 = (t: number) => Math.min(1, Math.max(0, t));
const smooth = (a: number, b: number, t: number) => ease(clamp01((t - a) / (b - a)));

/** live front edge (room z of the top rim) — keep in sync with gen_slab.py liveZ() */
export function liveZ(x: number) {
  const base = 0.166 + 0.006 * Math.sin(x * 5.3 + 0.9) + 0.0035 * Math.sin(x * 13.1 + 2.2) + 0.0014 * Math.sin(x * 41.0 + 0.4);
  const e0 = clamp01((x - SLAB.x0) / 0.16), e1 = clamp01((SLAB.x1 - x) / 0.16);
  return base - 0.012 * (1 - ease(e0)) - 0.01 * (1 - ease(e1));
}

// hashed value noise (deterministic)
function hash(i: number, j: number) {
  const s = Math.sin(i * 127.1 + j * 311.7) * 43758.5453;
  return s - Math.floor(s);
}
function vnoise(x: number, y: number) {
  const i = Math.floor(x), j = Math.floor(y), fx = x - i, fy = y - j;
  const u = ease(fx), v = ease(fy);
  const a = hash(i, j), b = hash(i + 1, j), c = hash(i, j + 1), d = hash(i + 1, j + 1);
  return (a * (1 - u) + b * u) * (1 - v) + (c * (1 - u) + d * u) * v - 0.5;
}

