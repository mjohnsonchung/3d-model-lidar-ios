    const wz = 0.036, wy = onTop(0, wz);
    mbat.add(rb(0.012, 0.004, 0.03, 0.0015, 1), dark, T(0, wy - 0.0012, wz));
    mbat.add(cyl(0.0105, 0.0105, 0.0078, 36), steel, T(0, wy - 0.007, wz, 0, 0, Math.PI / 2));
