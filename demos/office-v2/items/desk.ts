// MONITOR (BenQ RD280U: 610.4 × 427.8 mm, 87 mm deep; screen 596 × 397)

const MON = { w: 0.6104, h: 0.4278, sw: 0.5962, sh: 0.3975, top: 0.007, depth: 0.087 };

/** rear shell: a pillow that bulges from 12 mm at the rim to ~36 mm deep, local z ≤ 0 */
function monitorShell() {
  const nx = 48, ny = 36;
  const { w, h } = MON;
  const r = 0.008;
  const g = new THREE.PlaneGeometry(w, h, nx, ny);
  const p = g.getAttribute('position');
  for (let i = 0; i < p.count; i++) {
    const x = p.getX(i), y = p.getY(i);
    // distance to the rim (rounded rect), 0 at the edge
    const dx = w / 2 - Math.abs(x), dy = h / 2 - Math.abs(y);
    const dRim = Math.min(dx, dy);
    const depth = 0.013 + 0.024 * ease(clamp01(dRim / 0.13));
    p.setZ(i, depth); // becomes -depth after the rotateY(π) below
  }
  // shape the corners: pull outer vertices inside the rounded rect
  for (let i = 0; i < p.count; i++) {
    const x = p.getX(i), y = p.getY(i);
    const cx = w / 2 - r, cy = h / 2 - r;
    const ax = Math.abs(x), ay = Math.abs(y);
    if (ax > cx && ay > cy) {
      const vx = ax - cx, vy = ay - cy, l = Math.hypot(vx, vy);
      if (l > r) {
        p.setX(i, Math.sign(x) * (cx + (vx / l) * r));
        p.setY(i, Math.sign(y) * (cy + (vy / l) * r));
      }
    }
  }
  g.rotateY(Math.PI); // face -z (backwards)
  // after rotateY(π) x is mirrored; UVs stay as generated (u across the back as seen from behind)
  g.computeVertexNormals();
  return g;
}

/** side band joining the front bezel (z=0..-0.004) to the shell rim (z=-0.013) */
function monitorRim() {
  const s = roundedRectShape(MON.w - 0.0028, MON.h - 0.0028, 0.007); // inset so the silver bevel stays behind the black bezel
  const g = new THREE.ExtrudeGeometry(s, { depth: 0.012, bevelEnabled: true, bevelThickness: 0.0012, bevelSize: 0.0012, bevelSegments: 2, curveSegments: 6 });
  g.translate(0, 0, -0.0132);
  return g;
}

