/** textures are preloaded in build() (so captures never see a half-loaded slab); this just configures them */
function load(file: string, srgb = true, repeat = false) {
  const t = cache.get(file)!.clone();
  t.needsUpdate = true;
  t.colorSpace = srgb ? THREE.SRGBColorSpace : THREE.NoColorSpace;
  t.anisotropy = 8;
  if (repeat) t.wrapS = t.wrapT = THREE.RepeatWrapping;
  return t;
}

function canvasTex(w: number, h: number, draw: (c: CanvasRenderingContext2D, w: number, h: number) => void, srgb = true, repeat = false) {
  const cv = document.createElement('canvas');
  cv.width = w;
  cv.height = h;
  draw(cv.getContext('2d')!, w, h);
  const t = new THREE.CanvasTexture(cv);
  t.colorSpace = srgb ? THREE.SRGBColorSpace : THREE.NoColorSpace;
  t.anisotropy = 8;
  if (repeat) t.wrapS = t.wrapT = THREE.RepeatWrapping;
  return t;
}

/** tileable fine noise normal map (powder coat orange-peel, bead-blasted aluminium, plastic grain) */
function noiseNormal(size: number, scale: number, strength: number, seed: number) {
  return canvasTex(size, size, (c, w, h) => {
    const hgt = new Float32Array(w * h);
    for (let y = 0; y < h; y++)
      for (let x = 0; x < w; x++) {
        let v = 0, amp = 1, f = scale;
        for (let o = 0; o < 3; o++) {
          // periodic noise: wrap lattice at w/f
          const p = Math.max(1, Math.round(w / f));
          const X = (x / w) * p, Y = (y / h) * p;
          const i = Math.floor(X), j = Math.floor(Y), fx = X - i, fy = Y - j;
          const hh = (a: number, b: number) => hash(((a % p) + p) % p + seed * 17, ((b % p) + p) % p + seed * 31);
          const u = ease(fx), vv = ease(fy);
          v += amp * ((hh(i, j) * (1 - u) + hh(i + 1, j) * u) * (1 - vv) + (hh(i, j + 1) * (1 - u) + hh(i + 1, j + 1) * u) * vv);
          amp *= 0.5;
          f *= 2.3;
        }
        hgt[y * w + x] = v;
      }
    const img = c.createImageData(w, h);
    const H = (x: number, y: number) => hgt[((y + h) % h) * w + ((x + w) % w)];
    for (let y = 0; y < h; y++)
      for (let x = 0; x < w; x++) {
        const dx = (H(x + 1, y) - H(x - 1, y)) * strength, dy = (H(x, y + 1) - H(x, y - 1)) * strength;
        const n = new THREE.Vector3(-dx, dy, 1).normalize();
        const i = (y * w + x) * 4;
        img.data[i] = (n.x * 0.5 + 0.5) * 255;
        img.data[i + 1] = (n.y * 0.5 + 0.5) * 255;
        img.data[i + 2] = (n.z * 0.5 + 0.5) * 255;
        img.data[i + 3] = 255;
      }
    c.putImageData(img, 0, 0);
  }, false, true);
}

