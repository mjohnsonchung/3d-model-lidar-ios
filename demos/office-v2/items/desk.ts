    const nrm = body.getAttribute('normal');
    if (nrm.getY(NA * 2) < 0) {
      for (let i = 0; i < idx.length; i += 3) [idx[i + 1], idx[i + 2]] = [idx[i + 2], idx[i + 1]];
      body.setIndex(idx);
      body.computeVertexNormals();
    }
    const mbat = new Batch();
    mbat.add(body, shell);
    mbat.add(new THREE.ShapeGeometry(new THREE.Shape(ring.map((q) => new THREE.Vector2(q.x * 0.97, -q.z * 0.97)))).rotateX(-Math.PI / 2), dark, T(0, 0.0012, 0));
    // surface helper for small parts
    const onTop = (x: number, z: number) => topH(x, z);
